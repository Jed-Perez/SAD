CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','staff','technician','customer') NOT NULL DEFAULT 'customer',
 phone VARCHAR(40) NOT NULL DEFAULT '', address VARCHAR(500) NOT NULL DEFAULT '',
 active TINYINT(1) NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS products (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, sku VARCHAR(60) NOT NULL UNIQUE,
 name VARCHAR(160) NOT NULL, category VARCHAR(60) NOT NULL,
 price DECIMAL(12,2) NOT NULL DEFAULT 0, stock INT NOT NULL DEFAULT 0,
 reorder_level INT NOT NULL DEFAULT 5, active TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS services (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, customer_id INT UNSIGNED NOT NULL,
 technician_id INT UNSIGNED NULL, type ENUM('Installation','Repair','Maintenance') NOT NULL,
 title VARCHAR(160) NOT NULL, description TEXT NOT NULL, address VARCHAR(500) NOT NULL,
 status ENUM('Pending','Scheduled','In Progress','Completed','Cancelled') NOT NULL DEFAULT 'Pending',
 scheduled_at DATETIME NULL, duration_minutes INT NOT NULL DEFAULT 120,
 notes TEXT NULL, warranty_until DATE NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES users(id), FOREIGN KEY(technician_id) REFERENCES users(id),
 INDEX(technician_id,scheduled_at), INDEX(customer_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS stock_movements (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id INT UNSIGNED NOT NULL,
 user_id INT UNSIGNED NOT NULL, service_id INT UNSIGNED NULL,
 quantity INT NOT NULL, reason VARCHAR(255) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(product_id) REFERENCES products(id), FOREIGN KEY(user_id) REFERENCES users(id),
 FOREIGN KEY(service_id) REFERENCES services(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS service_events (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, service_id INT UNSIGNED NOT NULL,
 user_id INT UNSIGNED NOT NULL, description TEXT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(service_id) REFERENCES services(id), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS messages (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, customer_id INT UNSIGNED NOT NULL,
 sender_id INT UNSIGNED NOT NULL, body TEXT NOT NULL, read_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES users(id), FOREIGN KEY(sender_id) REFERENCES users(id),
 INDEX(customer_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS blueprints (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 title VARCHAR(160) NOT NULL, filename VARCHAR(80) NOT NULL, mime VARCHAR(40) NOT NULL,
 budget DECIMAL(12,2) NOT NULL DEFAULT 0, notes TEXT NOT NULL,
 analysis LONGTEXT NULL, estimate LONGTEXT NULL,
 status ENUM('Uploaded','Analyzing','Analyzed','Failed') NOT NULL DEFAULT 'Uploaded',
 reviewed_at DATETIME NULL, review_notes TEXT NULL, analysis_started_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS settings (
 setting_key VARCHAR(80) PRIMARY KEY, setting_value TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, fingerprint CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX(fingerprint,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NULL,
 action VARCHAR(120) NOT NULL, details VARCHAR(500) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
