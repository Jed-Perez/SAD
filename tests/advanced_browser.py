"""End-to-end checks for the new interfaces, with real AJAX persistence."""
import datetime


def advanced_browser(browser, port, password, bid, check, artifacts):
    context=browser.new_context(viewport={'width':1440,'height':1000})
    page=context.new_page();errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(f'http://127.0.0.1:{port}/portal.php')
    page.locator('#login-email').fill('admin@ncpcs.local');page.locator('#login-password').fill(password);page.locator('#auth-submit').click()
    page.locator('#content h1').wait_for()
    for route,heading in [('booking','Book a visit'),('forecast','Inventory forecast'),('quotations','Quotations'),('notifications','Notifications')]:
        page.goto(f'http://127.0.0.1:{port}/portal.php#{route}')
        page.get_by_role('heading',name=heading,exact=True).wait_for()
        check(not page.locator('#content > .alert-danger').count(),'Advanced browser renders '+route)
    page.goto(f'http://127.0.0.1:{port}/portal.php#messages/3')
    page.locator('.chat-header').wait_for()
    check('Other Customer' in page.locator('.chat-header').inner_text(),'Notification conversation link opens the intended customer')
    page.goto(f'http://127.0.0.1:{port}/portal.php#notifications')
    page.locator('#content h1').wait_for()
    page.locator('#notification-bell').click();page.locator('#notification-menu a[href="#notifications"]').wait_for()
    check(page.locator('#notification-menu').is_visible(),'Notification bell opens updates')
    page.keyboard.press('Escape')
    check(page.locator('#notification-menu').is_hidden(),'Notification menu dismisses with Escape')
    page.goto(f'http://127.0.0.1:{port}/portal.php#planner/{bid}')
    page.locator('#edit-camera-plan').click();page.locator('.editor-marker').first.wait_for()
    count=page.locator('.editor-marker').count()
    page.locator('#camera-add').click();check(page.locator('.editor-marker').count()==count+1,'Editor adds camera')
    page.locator('#plan-undo').click();check(page.locator('.editor-marker').count()==count,'Editor undo restores layout')
    page.locator('#plan-redo').click();check(page.locator('.editor-marker').count()==count+1,'Editor redo restores camera')
    page.locator('.editor-marker').last.focus();page.keyboard.press('ArrowRight');page.keyboard.press('r')
    check(page.locator('#f-camera_direction').input_value()=='15','Keyboard rotates camera')
    page.locator('#plan-save').click();page.wait_for_function("() => document.querySelector('#editor-status').textContent.includes('Saved version')")
    page.locator('#editor-price .workflow-card').first.wait_for()
    check(page.locator('#editor-price .workflow-card').count()==3,'Editor shows three catalog-based comparisons')
    page.screenshot(path=str(artifacts/'advanced-editor.png'),full_page=True,animations='disabled')
    page.locator('#editor-modal .btn-close').click();page.locator('#editor-modal').wait_for(state='hidden')
    page.reload();page.locator('#edit-camera-plan').click();page.locator('.editor-marker').first.wait_for()
    check(page.locator('.editor-marker').count()==count+1,'Camera edit survives reload')
    page.set_viewport_size({'width':390,'height':844})
    check(page.evaluate('document.documentElement.scrollWidth<=innerWidth'),'Interactive editor fits mobile')
    page.locator('#editor-modal .btn-close').click();page.locator('#editor-modal').wait_for(state='hidden')
    page.set_viewport_size({'width':1440,'height':1000})
    page.goto(f'http://127.0.0.1:{port}/portal.php#quotations')
    page.locator('#new-quotation').click()
    page.locator('#f-service_id').select_option(label='SR-2 · Other Customer · Other repair')
    page.locator('#quote-add-line').click();page.locator('#ql-quantity-0').fill('2');page.locator('#f-labor').fill('500')
    page.locator('#editor-form [type=submit]').click();page.locator('#quote-send').wait_for()
    check('Version 1' in page.locator('#content').inner_text(),'Quotation form saves a real draft')
    page.locator('#quote-send').click();page.locator('#editor-form [type=submit]').click();page.locator('#editor-modal').wait_for(state='hidden')
    page.wait_for_function("() => document.querySelector('#content').textContent.includes('Sent')")
    page.locator('#quote-revise').click();page.locator('#f-labor').fill('550');page.locator('#editor-form [type=submit]').click();page.locator('#quote-send').wait_for()
    check(page.locator('#f-quote_version option').count()==2,'Browser quotation revision retains prior version')
    page.screenshot(path=str(artifacts/'advanced-quotation.png'),full_page=True,animations='disabled')
    # Generate an actual PDF using the browser's print renderer.
    page.evaluate("window.print=()=>{};document.querySelector('#quote-print').click()")
    page.pdf(path=str(artifacts/'quotation-test.pdf'),format='A4',print_background=True)
    check((artifacts/'quotation-test.pdf').stat().st_size>1000,'Quotation print layout generates PDF')
    page.evaluate("document.body.classList.remove('print-advanced')")
    page.goto(f'http://127.0.0.1:{port}/portal.php#services/2')
    page.locator('#open-job-card').click();page.locator('#job-form').wait_for()
    page.locator('[data-check]').first.check();page.locator('#f-job_notes').fill('Browser checklist note')
    page.locator('#job-form [type=submit]').click();page.wait_for_function("() => document.querySelector('#f-job_notes')?.value==='Browser checklist note' && document.querySelector('#job-form [type=submit]')?.disabled===false")
    page.locator('#job-photo').click();page.locator('#f-photo').set_input_files(str(artifacts.parents[1]/'assets/images/products/outdoor-camera.webp'));page.locator('#f-caption').fill('Test installation photograph')
    page.locator('#editor-form [type=submit]').click();page.locator('#editor-modal').wait_for(state='hidden')
    page.reload();page.locator('#open-job-card').click();page.locator('.job-photos img').wait_for()
    check(page.locator('.job-photos img').count()==1,'Job photo uploads and reloads through protected endpoint')
    page.locator('#editor-modal .btn-close').click();page.locator('#editor-modal').wait_for(state='hidden')
    for width in [768,390,360]:
        page.set_viewport_size({'width':width,'height':900})
        for route in ['forecast','quotations','booking','notifications','schedule']:
            page.goto(f'http://127.0.0.1:{port}/portal.php#{route}')
            page.locator('#content h1').wait_for()
            check(page.evaluate('document.documentElement.scrollWidth<=innerWidth'),route+' fits '+str(width)+'px')
    page.screenshot(path=str(artifacts/'advanced-booking-mobile.png'),full_page=True,animations='disabled')
    customer=context.browser.new_context(viewport={'width':390,'height':844})
    cp=customer.new_page();cp.on('pageerror',lambda e:errors.append(str(e)))
    cp.goto(f'http://127.0.0.1:{port}/portal.php');cp.locator('#login-email').fill('customer@test.local');cp.locator('#login-password').fill('Customer-Test-123');cp.locator('#auth-submit').click()
    cp.locator('#support-launch').click();cp.locator('[data-question="My service status"]').click()
    cp.get_by_text('Your most recent saved requests:',exact=False).wait_for()
    check(cp.locator('#support-history').inner_text().find('Advanced visit')>=0,'Support widget retrieves verified service context')
    check(cp.evaluate('document.documentElement.scrollWidth<=innerWidth'),'Assistant fits mobile viewport')
    cp.locator('#support-close').click()
    cp.goto(f'http://127.0.0.1:{port}/portal.php#booking')
    day=datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=8))).date()+datetime.timedelta(days=17)
    cp.locator('#f-booking_date').fill(str(day));cp.locator('#booking-search button').click();cp.locator('[data-slot]').first.wait_for()
    check(cp.locator('#booking-calendar .available').count()>0,'Booking calendar displays actual available dates')
    cp.locator('[data-slot]').first.click()
    try:
        cp.locator('#f-address').wait_for(timeout=5000)
    except Exception:
        cp.screenshot(path=str(artifacts/'advanced-booking-failure.png'),full_page=True)
        print('Booking browser errors:',errors,'Notice:',cp.locator('#notice-body').inner_text())
        raise
    cp.locator('#f-address').fill('Browser booking address');cp.locator('#editor-form [type=submit]').click();cp.locator('#editor-modal').wait_for(state='hidden')
    cp.get_by_text('Installation visit',exact=True).first.wait_for()
    check(True,'Customer books an available visit through calendar workflow')
    check(not errors,'Advanced interfaces have no browser runtime errors: '+str(errors))
    customer.close();context.close()
